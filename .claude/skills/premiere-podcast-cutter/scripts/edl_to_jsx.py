#!/usr/bin/env python3
"""Turn an EDL into ONE Premiere Pro ExtendScript that builds every Short and trailer in a single run.

The script uses Premiere's own Sequence.createSubsequence(): for each range it sets the source sequence's
in/out, makes a subsequence (all video and audio tracks, every clip still separate and editable, sync kept),
renames it and files it in a bin. Shorts are then switched to 1080x1920 and their video clips scaled to fill
the frame. A trailer is built from one subsequence per beat (each fully editable), assembled in playback order
with createNewSequenceFromClips, with a marker per beat. The source sequence's own in/out marks are restored
at the end; nothing in it is edited.

Run the output with the Premiere MCP's raw-script tool (execute_extendscript and similar). The script returns a
one-line report per item.

Usage: edl_to_jsx.py edl.json --source-sequence "test-2" --prefix TEST2 [--bin "test-2_Cuts"] -o build.jsx
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_premiere_plan import slug  # noqa: E402

JSX = r"""// Generated by edl_to_jsx.py. Builds Shorts and trailers from "__SOURCE__" as editable multitrack sequences.
(function () {
var DATA = __DATA__;
var TPS = 254016000000;
var log = [];
function findSeq(name) {
  for (var i = 0; i < app.project.sequences.numSequences; i++) {
    if (app.project.sequences[i].name === name) return app.project.sequences[i];
  }
  return null;
}
function uniqueName(name) {
  var n = name, k = 2;
  while (findSeq(n)) { n = name + "_v" + k; k++; }
  return n;
}
function findOrMakeBin(parent, name) {
  for (var i = 0; i < parent.children.numItems; i++) {
    var c = parent.children[i];
    if (c.name === name && c.type === ProjectItemType.BIN) return c;
  }
  return parent.createBin(name);
}
function setRange(seq, start, end) {
  // Premiere versions differ: try ticks strings first, fall back to seconds; verify either way.
  seq.setInPoint(String(Math.round(start * TPS)));
  seq.setOutPoint(String(Math.round(end * TPS)));
  var got = seq.getInPointAsTime ? seq.getInPointAsTime().seconds : parseFloat(seq.getInPoint());
  if (Math.abs(got - start) > 0.05) { seq.setInPoint(start); seq.setOutPoint(end); }
  got = seq.getInPointAsTime ? seq.getInPointAsTime().seconds : parseFloat(seq.getInPoint());
  if (Math.abs(got - start) > 0.05) throw new Error("could not set in point " + start + " (got " + got + ")");
}
function subsequence(src, start, end, name, bin) {
  setRange(src, start, end);
  var s = src.createSubsequence(true);
  if (!s) throw new Error("createSubsequence returned nothing");
  s.name = uniqueName(name);
  try { s.projectItem.moveBin(bin); } catch (e) {}
  return s;
}
function reframeVertical(seq, w, h) {
  var st = seq.getSettings();
  var oldH = st.videoFrameHeight;
  st.videoFrameWidth = w; st.videoFrameHeight = h;
  seq.setSettings(st);
  var f = h / oldH, scaled = 0;
  for (var t = 0; t < seq.videoTracks.numTracks; t++) {
    var clips = seq.videoTracks[t].clips;
    for (var c = 0; c < clips.numItems; c++) {
      var comps = clips[c].components;
      for (var k = 0; k < comps.numItems; k++) {
        if (comps[k].displayName !== "Motion") continue;
        for (var p = 0; p < comps[k].properties.numItems; p++) {
          var prop = comps[k].properties[p];
          if (prop.displayName === "Scale") { prop.setValue(prop.getValue() * f, true); scaled++; }
        }
      }
    }
  }
  return scaled;
}
function addMarker(seq, seconds, name, comment) {
  var m = seq.markers.createMarker(seconds);
  m.name = name; m.comments = comment || "";
}
function trackSummary(seq) {
  var v = 0, a = 0;
  for (var t = 0; t < seq.videoTracks.numTracks; t++) v += seq.videoTracks[t].clips.numItems;
  for (var u = 0; u < seq.audioTracks.numTracks; u++) a += seq.audioTracks[u].clips.numItems;
  return seq.videoTracks.numTracks + "V/" + seq.audioTracks.numTracks + "A tracks, " + v + " video + " + a + " audio clips";
}

var src = findSeq(DATA.source);
if (!src) return "ERROR: no sequence named '" + DATA.source + "'";
var oldIn = src.getInPointAsTime ? src.getInPointAsTime().seconds : parseFloat(src.getInPoint());
var oldOut = src.getOutPointAsTime ? src.getOutPointAsTime().seconds : parseFloat(src.getOutPoint());
var bin = findOrMakeBin(app.project.rootItem, DATA.bin);

for (var i = 0; i < DATA.shorts.length; i++) {
  var it = DATA.shorts[i];
  try {
    var s = subsequence(src, it.start, it.end, it.name, bin);
    var n = (it.width && it.height && it.height > it.width) ? reframeVertical(s, it.width, it.height) : 0;
    addMarker(s, 0, it.title, it.note);
    log.push("OK  " + s.name + " | " + (it.end - it.start).toFixed(1) + " s | " + trackSummary(s) + " | scaled " + n + " video clips");
  } catch (e) { log.push("ERR " + it.name + " | " + e.message); }
}

for (var j = 0; j < DATA.trailers.length; j++) {
  var tr = DATA.trailers[j];
  try {
    var beatBin = findOrMakeBin(bin, tr.name + "_beats");
    var items = [], t0 = 0, starts = [];
    for (var b = 0; b < tr.beats.length; b++) {
      var bt = tr.beats[b];
      var bs = subsequence(src, bt.start, bt.end, tr.name + "_beat" + (b < 9 ? "0" : "") + (b + 1) + "_" + bt.role, beatBin);
      items.push(bs.projectItem); starts.push(t0); t0 += bt.end - bt.start;
    }
    var trailer = app.project.createNewSequenceFromClips(uniqueName(tr.name), items, bin);
    if (!trailer) throw new Error("createNewSequenceFromClips returned nothing");
    for (var m = 0; m < tr.beats.length; m++) addMarker(trailer, starts[m], "beat " + (m + 1) + " " + tr.beats[m].role, tr.beats[m].comment);
    log.push("OK  " + trailer.name + " | " + t0.toFixed(1) + " s | " + tr.beats.length + " beats (each an editable multitrack sequence in " + beatBin.name + ")");
  } catch (e2) { log.push("ERR " + tr.name + " | " + e2.message); }
}

try { setRange(src, oldIn, oldOut); } catch (e3) { log.push("WARN could not restore in/out on " + DATA.source); }
return log.join("\n");
})();
"""


def build(edl, source, prefix, bin_name):
    prefix = slug(prefix, 64).replace("-", "").upper()[:12] or "EP"
    shorts, trailers = [], []
    for n, c in enumerate([c for c in edl.get("clips", []) if c.get("type", "short") == "short"], 1):
        if c.get("start") is None or c.get("end") is None:
            continue
        mark = "" if c.get("verified") is True else "_UNVERIFIED"
        shorts.append({"name": f"{prefix}_SHORT_{n:02d}_{slug(c.get('title') or c['id'])}{mark}",
                       "title": c.get("upload_title") or c.get("title") or c["id"],
                       "note": " | ".join(x for x in (c.get("added_value"), c.get("notes")) if x),
                       "start": float(c["start"]), "end": float(c["end"]),
                       "width": c.get("width") or 1080, "height": c.get("height") or 1920})
    for n, t in enumerate(edl.get("trailers") or ([edl["trailer"]] if edl.get("trailer") else []), 1):
        beats = sorted(t.get("beats", []), key=lambda b: b["sequence"])
        if any(b.get("start") is None for b in beats):
            continue
        mark = "" if all(b.get("verified") is True for b in beats) else "_UNVERIFIED"
        trailers.append({"name": f"{prefix}_TRAILER_{n:02d}_{slug(t.get('concept') or t.get('id') or 'trailer')}{mark}",
                         "beats": [{"start": float(b["start"]), "end": float(b["end"]), "role": b.get("role") or "beat",
                                    "comment": " | ".join(x for x in (b.get("dialogue"), b.get("transition"), b.get("audio")) if x)}
                                   for b in beats]})
    data = {"source": source, "bin": bin_name, "shorts": shorts, "trailers": trailers}
    return JSX.replace("__SOURCE__", source).replace("__DATA__", json.dumps(data, ensure_ascii=True))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("edl")
    ap.add_argument("--source-sequence", required=True)
    ap.add_argument("--prefix", default="EP")
    ap.add_argument("--bin", default=None)
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()
    with open(args.edl, encoding="utf-8") as fh:
        edl = json.load(fh)
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(build(edl, args.source_sequence, args.prefix, args.bin or f"{args.source_sequence}_Cuts"))
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
